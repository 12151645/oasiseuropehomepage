export const formatPrice = (p: Property) => {
  const nf = new Intl.NumberFormat("en-GB", { style: "currency", currency: p.currency, maximumFractionDigits: 0 });
  return p.type === "rent" ? `${nf.format(p.price)} / month` : nf.format(p.price);
};
